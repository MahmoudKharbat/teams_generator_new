#!/usr/bin/env node
// Sets the app's login password. Writes only a salted hash to src/lib/authConfig.js;
// the password itself is printed once and never saved.
//
//   node scripts/hash-password.mjs            → generates a random password
//   node scripts/hash-password.mjs "my pass"  → uses the given password
//
// Changing the password signs out everyone who is logged in.
import { randomBytes, randomInt } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { deriveHash, ITERATIONS } from '../src/lib/passwordHash.js';

// No 0/o, 1/l/i, so it's easy to read out and type. 16 characters ≈ 79 bits of randomness.
const ALPHABET = 'abcdefghjkmnpqrstuvwxyz23456789';
const randomGroup = () => Array.from({ length: 4 }, () => ALPHABET[randomInt(ALPHABET.length)]).join('');

const password = process.argv[2] ?? Array.from({ length: 4 }, randomGroup).join('-');
const salt = randomBytes(16).toString('base64');
const hash = await deriveHash(password, { salt, iterations: ITERATIONS });

writeFileSync(
  new URL('../src/lib/authConfig.js', import.meta.url),
  `// Generated by scripts/hash-password.mjs. Only the salted hash is stored here, never the password.
export const PASSWORD_HASH = {
  iterations: ${ITERATIONS},
  salt: '${salt}',
  hash: '${hash}',
};
`
);

console.log(`Password: ${password}`);
console.log('Saved its hash to src/lib/authConfig.js. The password is not stored anywhere: copy it now.');
